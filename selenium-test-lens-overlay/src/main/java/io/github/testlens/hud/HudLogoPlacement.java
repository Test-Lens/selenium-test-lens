package io.github.testlens.hud;

/**
 * Selects a product-supported location for HUD branding.
 *
 * @since 0.3.0
 */
public enum HudLogoPlacement {
    /** Place branding in the compact rail beside the HUD content. */
    LEFT_RAIL,
    /** Place branding at the left edge of the header. */
    HEADER_LEFT,
    /** Place branding at the right edge of the header. */
    HEADER_RIGHT
}
